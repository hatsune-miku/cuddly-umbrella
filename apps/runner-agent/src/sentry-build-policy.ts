import { lstat, mkdir, readdir, readFile, realpath, writeFile } from 'node:fs/promises'
import path from 'node:path'
import ts from 'typescript'

// This package exists only in a disposable checkout. Never replace installed Sentry
// packages: pnpm may share their files with other jobs through its content store.
export const SENTRY_BUILD_SHIM = '@bifrost-build/sentry-disabled'

const pluginPackages = new Map([
  ['@sentry/webpack-plugin', { entry: 'webpack', factory: 'sentryWebpackPlugin' }],
  ['@sentry/webpack-plugin/webpack5', { entry: 'webpack', factory: 'sentryWebpackPlugin' }],
  ['@sentry/vite-plugin', { entry: 'vite', factory: 'sentryVitePlugin' }],
  ['@sentry/rollup-plugin', { entry: 'rollup', factory: 'sentryRollupPlugin' }],
  ['@sentry/esbuild-plugin', { entry: 'esbuild', factory: 'sentryEsbuildPlugin' }],
])

const excludedDirectories = new Set([
  '.git',
  'node_modules',
  'dist',
  'build',
  'coverage',
  '.next',
  '.nuxt',
  '.cache',
  '.turbo',
])

export interface SentryBuildRewrite {
  source: string
  references: number
  packages: string[]
}

function isModuleReference(node: ts.StringLiteralLike): boolean {
  const parent = node.parent
  if (ts.isImportDeclaration(parent))
    return parent.moduleSpecifier === node && !parent.importClause?.isTypeOnly
  if (ts.isExportDeclaration(parent)) return parent.moduleSpecifier === node && !parent.isTypeOnly
  if (ts.isExternalModuleReference(parent))
    return (
      parent.expression === node &&
      !(ts.isImportEqualsDeclaration(parent.parent) && parent.parent.isTypeOnly)
    )
  if (!ts.isCallExpression(parent) || parent.arguments[0] !== node) return false
  const callee = parent.expression
  return (
    callee.kind === ts.SyntaxKind.ImportKeyword ||
    (ts.isIdentifier(callee) && callee.text === 'require') ||
    (ts.isPropertyAccessExpression(callee) &&
      ts.isIdentifier(callee.expression) &&
      callee.expression.text === 'require' &&
      callee.name.text === 'resolve')
  )
}

/** Rewrite module specifiers, not plugin options or application Sentry SDK calls. */
export function rewriteSentryBuildImports(filename: string, source: string): SentryBuildRewrite {
  if (!source.includes('@sentry/')) return { source, references: 0, packages: [] }
  const file = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true)
  const replacements: { start: number; end: number; value: string }[] = []
  const packages = new Set<string>()
  function visit(node: ts.Node): void {
    if (ts.isStringLiteralLike(node) && isModuleReference(node)) {
      const plugin = pluginPackages.get(node.text)
      if (plugin) {
        // Each entry exposes the correct default API as well as the named factory.
        replacements.push({
          start: node.getStart(file),
          end: node.end,
          value: JSON.stringify(`${SENTRY_BUILD_SHIM}/${plugin.entry}`),
        })
        packages.add(node.text)
      } else if (
        /^@sentry\/(?:webpack|vite|rollup|esbuild|rspack|bun)-plugin(?:\/|$)|^@sentry\/bundler-plugins(?:\/|$)/.test(
          node.text
        )
      ) {
        throw new Error(`SENTRY_BUILD_PLUGIN_UNSUPPORTED: ${filename}: ${node.text}`)
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(file)
  if (replacements.length) {
    const diagnostics = (file as ts.SourceFile & { parseDiagnostics: readonly ts.Diagnostic[] })
      .parseDiagnostics
    if (diagnostics.length) {
      // Do not dump source or option values: config files can contain credentials.
      throw new Error(`SENTRY_BUILD_CONFIG_PARSE_FAILED: ${filename}`)
    }
  }
  let patched = source
  for (const replacement of replacements.sort((a, b) => b.start - a.start)) {
    patched =
      patched.slice(0, replacement.start) + replacement.value + patched.slice(replacement.end)
  }
  return { source: patched, references: replacements.length, packages: [...packages].sort() }
}

function shimImplementation(entry: string): string {
  const hooks = entry === 'webpack' ? ', apply() {}' : entry === 'esbuild' ? ', setup() {}' : ''
  return `// Generated by Bifrost. No real Sentry module is loaded.
function disabledSentryBuildPlugin() {
  return { name: 'bifrost-sentry-disabled'${hooks} };
}
`
}

async function ensureLocalDirectory(directory: string): Promise<void> {
  try {
    await mkdir(directory)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error
  }
  const stat = await lstat(directory)
  if (!stat.isDirectory() || stat.isSymbolicLink()) {
    throw new Error(`SENTRY_BUILD_SHIM_UNSAFE_PATH: ${directory}`)
  }
}

async function installShim(root: string): Promise<void> {
  const modules = path.join(root, 'node_modules')
  const scope = path.join(modules, '@bifrost-build')
  const directory = path.join(scope, 'sentry-disabled')
  await ensureLocalDirectory(modules)
  await ensureLocalDirectory(scope)
  // A pre-existing package is not ours to overwrite, even in a disposable job.
  try {
    await mkdir(directory)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error
    throw new Error(`SENTRY_BUILD_SHIM_COLLISION: ${directory}`)
  }
  const exports: Record<string, { import: string; require: string }> = {}
  for (const { entry, factory } of pluginPackages.values()) {
    if (exports[`./${entry}`]) continue
    exports[`./${entry}`] = { import: `./${entry}.mjs`, require: `./${entry}.cjs` }
    await writeFile(
      path.join(directory, `${entry}.mjs`),
      `${shimImplementation(entry)}
export { disabledSentryBuildPlugin as ${factory} };
export default disabledSentryBuildPlugin;
`,
      'utf8'
    )
    // Static assignments support Node's CommonJS named-export detection as well.
    await writeFile(
      path.join(directory, `${entry}.cjs`),
      `${shimImplementation(entry)}
module.exports = disabledSentryBuildPlugin;
module.exports.default = disabledSentryBuildPlugin;
module.exports.${factory} = disabledSentryBuildPlugin;
`,
      'utf8'
    )
  }
  await writeFile(
    path.join(directory, 'package.json'),
    `${JSON.stringify(
      {
        name: SENTRY_BUILD_SHIM,
        version: '1.0.0',
        private: true,
        exports,
      },
      null,
      2
    )}\n`,
    'utf8'
  )
}

/** Run after dependency installation, before any build command, for every adapter. */
export async function applySentryBuildPolicy(sourceDirectory: string): Promise<{
  files: number
  references: number
  packages: string[]
}> {
  const root = await realpath(sourceDirectory)
  const changes: { filename: string; source: string }[] = []
  const packages = new Set<string>()
  let references = 0
  async function visit(directory: string): Promise<void> {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const filename = path.join(directory, entry.name)
      // No symlink traversal, including source links and installed dependencies.
      if (entry.isDirectory() && !excludedDirectories.has(entry.name)) {
        await visit(filename)
      } else if (
        entry.isFile() &&
        /\.[cm]?[jt]sx?$/i.test(entry.name) &&
        !/\.d\.[cm]?ts$/i.test(entry.name)
      ) {
        const source = await readFile(filename, 'utf8')
        const result = rewriteSentryBuildImports(filename, source)
        if (!result.references) continue
        changes.push({ filename, source: result.source })
        references += result.references
        for (const specifier of result.packages) packages.add(specifier)
      }
    }
  }
  await visit(root)
  if (changes.length) {
    await installShim(root)
    for (const change of changes) await writeFile(change.filename, change.source, 'utf8')
  }
  return { files: changes.length, references, packages: [...packages].sort() }
}
